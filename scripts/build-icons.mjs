// and simple-icons (CC0) brand marks. Run: node scripts/build-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const line = `arrow-right arrow-up-right chevron-down chevron-right chevron-left plus minus x menu phone mail map-pin clock globe
heart-pulse shield-check stethoscope users user-round briefcase building-2 car house umbrella file-text clipboard-check scale search
layers target trending-up compass graduation-cap book-open presentation lightbulb sparkles refresh-cw settings-2 chart-line hospital
activity badge-check calendar map monitor laptop crown puzzle network workflow route flag mountain key-round lock flame droplets
cloud-lightning wrench truck package factory landmark wallet receipt headset life-buoy check circle-check circle-help quote
heart-handshake baby hand-heart chart-no-axes-combined gauge eye messages-square calendar-check list-checks user-check shield
sun-medium leaf circle-dollar-sign file-search git-branch milestone rocket mic library video message-square-text send
external-link download info triangle-alert cookie log-in hand-coins scan-search shield-plus user-cog users-round building door-open
warehouse car-front siren clipboard-list notebook-pen chart-pie handshake zap
file-check chart-column camera images image award calendar-days user-round-check`.split(/\s+/).filter(Boolean);

const brands = { whatsapp: 'whatsapp', facebook: 'facebook', instagram: 'instagram', x: 'x', youtube: 'youtube', tiktok: 'tiktok',
  telegram: 'telegram', snapchat: 'snapchat', threads: 'threads', messenger: 'messenger' };

const symbols = [];
for (const name of line) {
  const svg = readFileSync(`node_modules/lucide-static/icons/${name}.svg`, 'utf8');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
  symbols.push(`<symbol id="i-${name}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">${inner}</symbol>`);
}
for (const [id, file] of Object.entries(brands)) {
  const svg = readFileSync(`node_modules/simple-icons/icons/${file}.svg`, 'utf8');
  const path = svg.match(/<path d="([^"]+)"/)[1];
  symbols.push(`<symbol id="b-${id}" viewBox="0 0 24 24" fill="currentColor"><path d="${path}"/></symbol>`);
}
// LinkedIn mark (drawn by hand; brand removed from simple-icons).
symbols.push('<symbol id="b-linkedin" viewBox="0 0 24 24" fill="currentColor"><path d="M4.98 3.5a2.5 2.5 0 1 1 0 5 2.5 2.5 0 0 1 0-5ZM3 9.75h4v11H3v-11Zm6.5 0h3.83v1.5h.06c.53-1 1.84-1.85 3.79-1.85 4.05 0 4.82 2.5 4.82 5.76v5.59h-4v-4.96c0-1.18-.02-2.7-1.65-2.7-1.65 0-1.9 1.29-1.9 2.62v5.04h-3.95v-11Z"/></symbol>');

writeFileSync('public/images/icons.svg', `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">${symbols.join('')}</svg>\n`);
writeFileSync('app/Support/icon-list.php', `<?php\n\n// Generated by scripts/build-icons.mjs\nreturn ${JSON.stringify(line).replace(/^\[/, '[').replace(/"/g, "'")};\n`);
console.log(`icons.svg: ${symbols.length} symbols`);
